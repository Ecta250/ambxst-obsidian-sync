#!/usr/bin/env python3
"""Keep an "ambxst" CSS snippet in each Obsidian vault in the Ambxst colours.

Vaults are the ones Obsidian lists in obsidian.json (native and Flatpak), or
explicit paths given with --vault. The snippet is written to
.obsidian/snippets/ambxst.css; Obsidian reloads enabled snippets when their file
changes, so open windows follow the theme at once.

With --enable, the snippet is turned on in appearance.json the first time it is
written. Turning it off in Obsidian afterwards is respected. With --match-mode,
Obsidian's base theme (dark or light) follows the Ambxst palette.
"""

import argparse
import colorsys
import json
import os
import sys
import tempfile

SNIPPET = "ambxst"
# Marks vaults where the snippet was already enabled once, so a user who turns
# it off in Obsidian keeps it off.
MARKER = ".ambxst-snippet-enabled"


def expand(path):
    return os.path.abspath(os.path.expanduser(path))


def obsidian_configs():
    config = os.environ.get("XDG_CONFIG_HOME") or expand("~/.config")
    return (
        os.path.join(config, "obsidian", "obsidian.json"),
        expand("~/.var/app/md.obsidian.Obsidian/config/obsidian/obsidian.json"),
    )


def read(path):
    try:
        with open(path, encoding="utf-8") as handle:
            return handle.read()
    except FileNotFoundError:
        return None


def read_json(path):
    try:
        data = json.loads(read(path) or "{}")
    except json.JSONDecodeError:
        return None
    return data if isinstance(data, dict) else None


def write_atomic(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=os.path.dirname(path), prefix=".ambxst-obsidian-")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(content)
        os.chmod(tmp, 0o644)
        os.replace(tmp, path)
    except BaseException:
        os.unlink(tmp)
        raise


def vault_dirs(explicit):
    if explicit:
        candidates = [expand(path) for path in explicit]
    else:
        candidates = []
        for config in obsidian_configs():
            vaults = (read_json(config) or {}).get("vaults") or {}
            candidates += [entry.get("path") for entry in vaults.values() if isinstance(entry, dict)]
    found = []
    for path in candidates:
        if path and os.path.isdir(os.path.join(path, ".obsidian")) and path not in found:
            found.append(path)
    return found


def hex_rgb(hex_colour):
    digits = hex_colour.lstrip("#")
    return tuple(int(digits[i:i + 2], 16) for i in (0, 2, 4))


def rgb_triplet(hex_colour):
    return ", ".join(str(part) for part in hex_rgb(hex_colour))


def mix(a, b, amount):
    """a moved towards b by amount (0..1), in sRGB."""
    return "#" + "".join(
        f"{round(x + (y - x) * amount):02x}" for x, y in zip(hex_rgb(a), hex_rgb(b))
    )


def is_dark(hex_colour):
    red, green, blue = hex_rgb(hex_colour)
    return 0.2126 * red + 0.7152 * green + 0.0722 * blue < 128


def accent_hsl(hex_colour):
    red, green, blue = (part / 255 for part in hex_rgb(hex_colour))
    hue, light, sat = colorsys.rgb_to_hls(red, green, blue)
    return round(hue * 360), f"{round(sat * 100)}%", f"{round(light * 100)}%"


# Obsidian's grey scale, as a fraction of the way from background to text.
BASE_STEPS = {
    "00": 0.0, "05": 0.02, "10": 0.04, "20": 0.07, "25": 0.09, "30": 0.15,
    "35": 0.2, "40": 0.3, "50": 0.4, "60": 0.6, "70": 0.75, "100": 0.92,
}


def snippet_css(colours):
    c = colours
    bg, fg = c["background"], c["overBackground"]
    hue, sat, light = accent_hsl(c["primary"])
    orange = mix(c["red"], c["yellow"], 0.5)
    purple = mix(c["blue"], c["magenta"], 0.5)

    named = {
        "red": c["red"], "orange": orange, "yellow": c["yellow"], "green": c["green"],
        "cyan": c["cyan"], "blue": c["blue"], "purple": purple, "pink": c["magenta"],
    }

    lines = [f"  --color-base-{step}: {mix(bg, fg, amount)};" for step, amount in BASE_STEPS.items()]
    for name, value in named.items():
        lines.append(f"  --color-{name}: {value};")
        lines.append(f"  --color-{name}-rgb: {rgb_triplet(value)};")
    base = "\n".join(lines)

    return f"""/* Generated by the Obsidian Sync mod for Ambxst. Rewritten on every theme change. */

body.theme-dark,
body.theme-light {{
{base}

  --accent-h: {hue};
  --accent-s: {sat};
  --accent-l: {light};
  --color-accent: {c["primary"]};
  --color-accent-1: color-mix(in srgb, {c["primary"]} 88%, {fg});
  --color-accent-2: color-mix(in srgb, {c["primary"]} 76%, {fg});

  --background-primary: {bg};
  --background-primary-alt: {c["surfaceContainerLow"]};
  --background-secondary: {c["surfaceContainerLow"]};
  --background-secondary-alt: {c["surfaceContainer"]};
  --background-modifier-border: {c["outlineVariant"]};
  --background-modifier-border-hover: {c["outline"]};
  --background-modifier-border-focus: {c["primary"]};
  --background-modifier-hover: rgba({rgb_triplet(fg)}, 0.07);
  --background-modifier-active-hover: rgba({rgb_triplet(c["primary"])}, 0.15);
  --background-modifier-form-field: {c["surfaceContainerHigh"]};
  --background-modifier-error: {c["error"]};
  --background-modifier-error-hover: {c["error"]};
  --background-modifier-success: {c["green"]};
  --background-modifier-message: {c["inverseSurface"]};
  --background-modifier-cover: rgba({rgb_triplet(c["scrim"])}, 0.6);

  --text-normal: {fg};
  --text-muted: {c["overSurfaceVariant"]};
  --text-faint: {c["outline"]};
  --text-on-accent: {c["overPrimary"]};
  --text-on-accent-inverted: {c["overPrimary"]};
  --text-accent: {c["primary"]};
  --text-accent-hover: var(--color-accent-2);
  --text-error: {c["error"]};
  --text-success: {c["green"]};
  --text-warning: {orange};
  --text-selection: rgba({rgb_triplet(c["primary"])}, 0.3);
  --text-highlight-bg: rgba({rgb_triplet(c["yellow"])}, 0.3);
  --text-highlight-bg-active: rgba({rgb_triplet(c["yellow"])}, 0.5);
  --caret-color: {c["primary"]};

  --interactive-normal: {c["surfaceContainerHigh"]};
  --interactive-hover: {c["surfaceContainerHighest"]};
  --interactive-accent: {c["primary"]};
  --interactive-accent-hover: var(--color-accent-1);
  --interactive-accent-hsl: var(--accent-h), var(--accent-s), var(--accent-l);

  --titlebar-background: {c["surfaceContainerLow"]};
  --titlebar-background-focused: {c["surfaceContainer"]};
  --ribbon-background: {c["surfaceContainerLow"]};
  --ribbon-background-collapsed: {bg};
  --tab-container-background: {c["surfaceContainerLow"]};
  --modal-background: {c["surfaceContainer"]};
  --scrollbar-thumb-bg: rgba({rgb_triplet(fg)}, 0.15);
  --scrollbar-active-thumb-bg: rgba({rgb_triplet(fg)}, 0.25);
  --divider-color: {c["outlineVariant"]};

  --link-color: {c["primary"]};
  --link-color-hover: var(--color-accent-2);
  --link-external-color: {c["tertiary"]};
  --link-external-color-hover: color-mix(in srgb, {c["tertiary"]} 76%, {fg});
  --link-unresolved-color: {c["primary"]};
  --tag-color: {c["primary"]};
  --tag-color-hover: {c["primary"]};
  --tag-background: rgba({rgb_triplet(c["primary"])}, 0.12);
  --tag-background-hover: rgba({rgb_triplet(c["primary"])}, 0.2);
  --blockquote-border-color: {c["primary"]};
  --checkbox-color: {c["primary"]};
  --checkbox-color-hover: var(--color-accent-1);
  --checkbox-marker-color: {c["overPrimary"]};

  --code-background: {c["surfaceContainerLow"]};
  --code-normal: {c["overSurface"]};
  --code-comment: {c["outline"]};
  --code-function: {c["blue"]};
  --code-important: {c["red"]};
  --code-keyword: {c["magenta"]};
  --code-operator: {c["overSurfaceVariant"]};
  --code-property: {c["cyan"]};
  --code-punctuation: {c["overSurfaceVariant"]};
  --code-string: {c["green"]};
  --code-tag: {c["red"]};
  --code-value: {c["yellow"]};

  --graph-line: {c["outlineVariant"]};
  --graph-node: {c["overSurfaceVariant"]};
  --graph-node-unresolved: {c["outline"]};
  --graph-node-focused: {c["primary"]};
  --graph-node-tag: {c["green"]};
  --graph-node-attachment: {c["yellow"]};
}}
"""


def update_appearance(vault, enable, mode):
    """Turn the snippet on once and set the base theme. Returns True if written."""
    config = os.path.join(vault, ".obsidian")
    path = os.path.join(config, "appearance.json")
    appearance = read_json(path)
    if appearance is None:
        return False
    before = dict(appearance)

    marker = os.path.join(config, "snippets", MARKER)
    if enable and not os.path.exists(marker):
        snippets = appearance.get("enabledCssSnippets")
        if not isinstance(snippets, list):
            snippets = []
        if SNIPPET not in snippets:
            appearance["enabledCssSnippets"] = snippets + [SNIPPET]
        write_atomic(marker, "")
    if mode:
        appearance["theme"] = mode

    if appearance == before:
        return False
    write_atomic(path, json.dumps(appearance, indent=2) + "\n")
    return True


def sync_vault(vault, css, enable, mode):
    path = os.path.join(vault, ".obsidian", "snippets", SNIPPET + ".css")
    changed = False
    if read(path) != css:
        write_atomic(path, css)
        changed = True
    return update_appearance(vault, enable, mode) or changed


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--vault", action="append", default=[],
                        help="Obsidian vault folder; repeatable. Default: the vaults Obsidian knows")
    parser.add_argument("--colors", default=expand("~/.cache/ambxst/colors.json"))
    parser.add_argument("--enable", action="store_true",
                        help="Turn the snippet on in each vault the first time")
    parser.add_argument("--match-mode", action="store_true",
                        help="Switch Obsidian between dark and light with the Ambxst palette")
    args = parser.parse_args()

    colours = read_json(args.colors)
    if not colours or "background" not in colours:
        print(f"obsidian_sync: no palette in {args.colors}", file=sys.stderr)
        return 1

    vaults = vault_dirs(args.vault)
    if not vaults:
        print("obsidian_sync: no Obsidian vault found", file=sys.stderr)
        return 1

    try:
        css = snippet_css(colours)
    except KeyError as missing:
        print(f"obsidian_sync: colour {missing} missing from {args.colors}", file=sys.stderr)
        return 1

    mode = None
    if args.match_mode:
        mode = "obsidian" if is_dark(colours["background"]) else "moonstone"

    for vault in vaults:
        if sync_vault(vault, css, args.enable, mode):
            print(f"obsidian_sync: updated {vault}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
